#!/usr/bin/env python3
"""
ROI Report — weekly Telegram summary of Tenazas value.

Reads roi_state.json (generated by roi_tracker.py) and formats
a human-readable report for Telegram.

Usage:
    python3 roi_report.py              # print report
    python3 roi_report.py --json       # raw JSON
    python3 roi_report.py --send       # send to Telegram
    python3 roi_report.py --days 30    # custom period
"""

import json
import sys
from datetime import datetime, timedelta
from pathlib import Path
from urllib.request import urlopen, Request

try:
    from .runtime_config import get_default_telegram_chat_id
except ImportError:
    from runtime_config import get_default_telegram_chat_id

CHAT_ID = get_default_telegram_chat_id()


def _load_snapshot():
    """Load existing roi_state.json."""
    state_file = Path(__file__).parent / "logs" / "roi_state.json"
    if not state_file.exists():
        return None
    try:
        return json.loads(state_file.read_text())
    except Exception:
        return None


def _notify(msg):
    """Send message to Telegram."""
    try:
        config = json.loads(open("/home/tenazas/.openclaw/openclaw.json").read())
        token = config["channels"]["telegram"]["botToken"]
        payload = json.dumps({
            "chat_id": CHAT_ID,
            "text": msg[:4090],
            "parse_mode": "HTML",
        }).encode()
        urlopen(Request(
            f"https://api.telegram.org/bot{token}/sendMessage",
            data=payload,
            headers={"Content-Type": "application/json"},
        ), timeout=10)
        return True
    except Exception:
        # Retry without parse_mode if HTML fails
        try:
            payload = json.dumps({
                "chat_id": CHAT_ID,
                "text": msg[:4090],
            }).encode()
            urlopen(Request(
                f"https://api.telegram.org/bot{token}/sendMessage",
                data=payload,
                headers={"Content-Type": "application/json"},
            ), timeout=10)
            return True
        except Exception:
            return False


def format_report(data):
    """Format ROI snapshot as Telegram-friendly text."""
    if not data:
        return "ROI: sin datos. Correr roi_tracker.py primero."

    t = data.get("totals", {})
    days = data.get("period_days", 7)
    now = datetime.now()
    start = (now - timedelta(days=days)).strftime("%d/%m")
    end = now.strftime("%d/%m")

    lines = [f"Reporte ROI Semanal - {start} al {end}"]
    lines.append("")

    # Automation
    skills = t.get("skill_executions", 0)
    chats = t.get("llm_chats", 0)
    rate = int(t.get("automation_rate", 0) * 100)
    lines.append(f"Automatizaciones: {skills} skills vs {chats} chats")
    lines.append(f"Tasa de automatizacion: {rate}%")
    lines.append("")

    # Hours saved
    hours = t.get("hours_saved", 0)
    mins = t.get("minutes_saved", 0)
    lines.append(f"Tiempo ahorrado: ~{hours}h (~{mins} min)")
    top_hours = sorted(
        data.get("hours_saved_detail", {}).items(),
        key=lambda x: x[1], reverse=True
    )[:3]
    if top_hours:
        parts = [f"{k.replace('skill:', '')}({v}h)" for k, v in top_hours]
        lines.append(f"  Top: {', '.join(parts)}")
    lines.append("")

    # Errors avoided
    ea = data.get("errors_avoided_detail", {})
    total_ea = ea.get("total", 0)
    parts = []
    if ea.get("container_restarts"):
        parts.append(f"{ea['container_restarts']} container restarts")
    if ea.get("vpn_fixes"):
        parts.append(f"{ea['vpn_fixes']} VPN fixes")
    if ea.get("ollama_recoveries"):
        parts.append(f"{ea['ollama_recoveries']} Ollama recoveries")
    lines.append(f"Errores evitados: {total_ea}")
    if parts:
        lines.append(f"  {', '.join(parts)}")
    lines.append("")

    # Top skills
    top = data.get("top_skills", [])[:7]
    if top:
        lines.append(f"Top skills ({days}d):")
        for i, (name, count) in enumerate(top, 1):
            info = data.get("skills", {}).get(name, {})
            sr = int(info.get("success_rate", 0) * 100)
            clean = name.replace("skill:", "")
            lines.append(f"  {i}. {clean}: {count} ({sr}%)")
        lines.append("")

    # Unused skills (in MINUTES_SAVED but count=0)
    from roi_tracker import MINUTES_SAVED
    used = set(data.get("skills", {}).keys())
    unused = [k.replace("skill:", "") for k in MINUTES_SAVED
              if k.startswith("skill:") and k not in used and MINUTES_SAVED[k] > 0]
    if unused:
        lines.append(f"Skills sin uso: {', '.join(unused)}")
        lines.append("")

    lines.append(f">> Tenazas te ahorro ~{hours} horas esta semana")

    return "\n".join(lines)


def main():
    days = 7
    as_json = False
    send = False

    for i, arg in enumerate(sys.argv[1:], 1):
        if arg == "--json":
            as_json = True
        elif arg == "--send":
            send = True
        elif arg == "--days" and i < len(sys.argv) - 1:
            days = int(sys.argv[i + 1])

    # Generate fresh snapshot
    from roi_tracker import generate_roi_snapshot
    data = generate_roi_snapshot(days)

    if as_json:
        print(json.dumps(data, indent=2, ensure_ascii=False))
        return

    report = format_report(data)

    if send:
        ok = _notify(report)
        print("Enviado a Telegram" if ok else "Error enviando a Telegram")
    else:
        print(report)


if __name__ == "__main__":
    main()
