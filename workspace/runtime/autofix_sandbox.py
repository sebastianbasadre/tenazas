#!/usr/bin/env python3
"""
autofix_sandbox.py — Git operations for autofix agent.

Branch, diff validation, merge, rollback — all with safety checks.
"""

import re
import subprocess
from datetime import datetime
from pathlib import Path

_IN_CONTAINER = Path("/home/tenazas").exists()
REPO_DIR = Path("/home/tenazas") if _IN_CONTAINER else Path(__file__).parent.parent


def git_is_clean() -> bool:
    """Check if working tree is clean."""
    try:
        r = subprocess.run(["git", "status", "--porcelain"],
                           capture_output=True, text=True, timeout=10,
                           cwd=str(REPO_DIR))
        return r.returncode == 0 and not r.stdout.strip()
    except Exception:
        return False


def create_branch(probe: str) -> str:
    """Create autofix branch. Returns branch name."""
    ts = datetime.now().strftime("%Y%m%d-%H%M%S")
    slug = re.sub(r'[^a-z0-9]', '-', probe.lower())[:20].strip('-')
    branch = f"autofix/{ts}-{slug}"
    subprocess.run(["git", "checkout", "-b", branch],
                   capture_output=True, cwd=str(REPO_DIR))
    return branch


def validate_diff(protected_files: list, max_lines: int = 50,
                  max_files: int = 3) -> dict:
    """Validate staged/unstaged changes against safety rules.

    Returns:
        {valid, files, insertions, deletions, reason}
    """
    try:
        r = subprocess.run(["git", "diff", "--stat"],
                           capture_output=True, text=True, timeout=10,
                           cwd=str(REPO_DIR))
        stat = r.stdout.strip()
        if not stat:
            return {"valid": False, "reason": "no changes made"}

        lines = stat.split("\n")
        summary_line = lines[-1] if lines else ""

        # Parse changed files
        changed = []
        for line in lines[:-1]:
            parts = line.strip().split("|")
            if parts:
                changed.append(parts[0].strip())

        # File count
        if len(changed) > max_files:
            return {"valid": False, "files": changed,
                    "reason": f"too many files: {len(changed)} (max {max_files})"}

        # Line count
        ins = 0
        dels = 0
        m = re.search(r"(\d+) insertion", summary_line)
        if m:
            ins = int(m.group(1))
        m = re.search(r"(\d+) deletion", summary_line)
        if m:
            dels = int(m.group(1))

        if ins + dels > max_lines:
            return {"valid": False, "files": changed,
                    "reason": f"too many changes: {ins + dels} lines (max {max_lines})"}

        # Protected files check
        for f in changed:
            for pf in protected_files:
                if pf in f or f in pf:
                    return {"valid": False, "files": changed,
                            "reason": f"protected file: {f}"}

        # Syntax check
        for f in changed:
            if f.endswith(".py"):
                full = REPO_DIR / f
                if full.exists():
                    r2 = subprocess.run(
                        ["python3", "-m", "py_compile", str(full)],
                        capture_output=True, text=True, timeout=10)
                    if r2.returncode != 0:
                        return {"valid": False, "files": changed,
                                "reason": f"syntax error: {f} — {r2.stderr[:200]}"}

        return {"valid": True, "files": changed,
                "insertions": ins, "deletions": dels}
    except Exception as e:
        return {"valid": False, "reason": str(e)}


def commit_fix(probe: str, model: str) -> bool:
    """Commit current changes as autofix."""
    try:
        subprocess.run(["git", "add", "-A"], capture_output=True, cwd=str(REPO_DIR))
        msg = (f"autofix: {probe} [claude-agent]\n\n"
               f"Auto-generated by autofix_agent Tier 2\n"
               f"Model: {model}")
        r = subprocess.run(["git", "commit", "-m", msg],
                           capture_output=True, text=True, cwd=str(REPO_DIR))
        return r.returncode == 0
    except Exception:
        return False


def merge_to_main(branch: str) -> dict:
    """Merge autofix branch to main."""
    try:
        subprocess.run(["git", "checkout", "main"],
                       capture_output=True, cwd=str(REPO_DIR))
        r = subprocess.run(["git", "merge", branch],
                           capture_output=True, text=True, cwd=str(REPO_DIR))
        if r.returncode != 0:
            return {"success": False, "reason": "merge conflict",
                    "stderr": r.stderr[:300]}
        # Get merge commit SHA
        sha_r = subprocess.run(["git", "rev-parse", "HEAD"],
                               capture_output=True, text=True, cwd=str(REPO_DIR))
        sha = sha_r.stdout.strip()[:12]
        # Delete branch
        subprocess.run(["git", "branch", "-d", branch],
                       capture_output=True, cwd=str(REPO_DIR))
        return {"success": True, "sha": sha}
    except Exception as e:
        return {"success": False, "reason": str(e)}


def rollback(sha: str) -> dict:
    """Revert a commit by SHA."""
    try:
        r = subprocess.run(["git", "revert", "--no-edit", sha],
                           capture_output=True, text=True, cwd=str(REPO_DIR))
        if r.returncode == 0:
            revert_sha = subprocess.run(
                ["git", "rev-parse", "HEAD"],
                capture_output=True, text=True, cwd=str(REPO_DIR)
            ).stdout.strip()[:12]
            return {"success": True, "reverted": sha, "revert_sha": revert_sha}
        return {"success": False, "reason": r.stderr[:300]}
    except Exception as e:
        return {"success": False, "reason": str(e)}


def cleanup_branch(branch: str):
    """Cleanup a failed branch — checkout main, delete branch, reset."""
    try:
        subprocess.run(["git", "checkout", "main"],
                       capture_output=True, cwd=str(REPO_DIR))
        subprocess.run(["git", "branch", "-D", branch],
                       capture_output=True, cwd=str(REPO_DIR))
        subprocess.run(["git", "checkout", "--", "."],
                       capture_output=True, cwd=str(REPO_DIR))
    except Exception:
        pass


def get_diff_summary() -> str:
    """Get short diff summary for Telegram."""
    try:
        r = subprocess.run(["git", "diff", "--stat"],
                           capture_output=True, text=True, timeout=10,
                           cwd=str(REPO_DIR))
        return r.stdout.strip()[:500]
    except Exception:
        return "(diff unavailable)"


def get_current_sha() -> str:
    """Get current HEAD SHA."""
    try:
        r = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                           capture_output=True, text=True, cwd=str(REPO_DIR))
        return r.stdout.strip()
    except Exception:
        return "unknown"
